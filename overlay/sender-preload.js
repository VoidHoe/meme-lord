const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('sender', {
  getSettings:    ()                 => ipcRenderer.invoke('get-settings'),
  saveSettings:   (settings)         => ipcRenderer.invoke('save-settings', settings),
  sendDrop:       (payload)          => ipcRenderer.invoke('send-drop', payload),
  resolveLink:    (url)              => ipcRenderer.invoke('resolve-link', url),
  uploadAudio:    (buf)              => ipcRenderer.invoke('upload-audio', buf),
  uploadMedia:    (buf, mime)        => ipcRenderer.invoke('upload-media', { buffer: buf, mimeType: mime }),
  getUsers:       ()                 => ipcRenderer.invoke('get-users'),
  searchGifs:     (query)            => ipcRenderer.invoke('search-gifs', query),
  getFavorites:   ()                 => ipcRenderer.invoke('get-favorites'),
  saveFavorite:   (fav)              => ipcRenderer.invoke('save-favorite', fav),
  deleteFavorite: (id)               => ipcRenderer.invoke('delete-favorite', id),
  saveHistory:    (entry)            => ipcRenderer.send('save-history', entry),
  getHistory:     ()                 => ipcRenderer.invoke('get-history'),
  clearHistory:   ()                 => ipcRenderer.invoke('clear-history'),
  libraryList:    ()                 => ipcRenderer.invoke('library-list'),
  librarySave:    (payload)          => ipcRenderer.invoke('library-save', payload),
  librarySaveBuffer: (buffer, name, situation) => ipcRenderer.invoke('library-save-buffer', { buffer, name, situation }),
  libraryDelete:  (id)               => ipcRenderer.invoke('library-delete', id),
  libraryUpload:  (id)               => ipcRenderer.invoke('library-upload', id),
  close:          ()                 => ipcRenderer.send('close-sender'),
  minimize:       ()                 => ipcRenderer.send('minimize-sender'),
  openSnipTool:   ()                 => ipcRenderer.invoke('open-snip-tool'),
  checkForUpdates:()                 => ipcRenderer.invoke('check-for-updates'),
  onUpdateStatus: (cb)               => ipcRenderer.on('update-status', (_e, msg) => cb(msg)),
  onShowTab:      (cb)               => ipcRenderer.on('show-tab',      (_e, tab) => cb(tab)),
  onSnipResult:   (cb)               => ipcRenderer.on('snip-result',   (_e, d)   => cb(d)),
});
